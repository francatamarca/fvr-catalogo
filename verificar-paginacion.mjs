import assert from 'node:assert/strict';
import fs from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {PRODUCTOS_POR_PAGINA,leerVista,urlVista,ventanaPaginas,retornoSeguro} from './lib/catalogo-navegacion.js';
const c=JSON.parse(gunzipSync(fs.readFileSync('data/catalogo.public.json.gz')));
const pages=Math.ceil(c.productos.length/PRODUCTOS_POR_PAGINA);
assert.equal(pages,231);assert.equal(c.productos.slice((pages-1)*48).length,25);
const seen=[];for(let n=1;n<=pages;n++)seen.push(...c.productos.slice((n-1)*48,n*48).map(p=>p.codigo));
assert.deepEqual(seen,c.productos.map(p=>p.codigo));assert.equal(new Set(seen).size,c.total);
const input='?q=iphone+18&categoria=celulares-y-smartphones&orden=mayor&min=10.5&max=2000&pagina=3&favoritos=1&catalogo=1&pestana=ofertas&marcaInicio=APPLE';
const view=leerVista(input);assert.deepEqual(leerVista(urlVista(view).slice(1)),view);
assert.equal(view.pagina,3);assert.equal(view.pMin,'10.5');assert.equal(view.favoritos,true);
for(const s of ['0','-1','abc','1.5','Infinity'])assert.equal(leerVista('?pagina='+s).pagina,1);
assert.equal(leerVista('?pagina=9999999').pagina,1000000);
assert.equal(leerVista('?min=NaN&max=-20').pMin,'');assert.equal(leerVista('?min=NaN&max=-20').pMax,'');
assert.equal(urlVista(leerVista()),'/');assert.equal(urlVista({...view,pagina:1}).includes('pagina='),false);
for(const target of ['https://evil.example/','//evil.example/','/\\evil.example/','javascript:alert(1)','/producto/123','/%2f%2fevil.example'])assert.equal(retornoSeguro(target),'/');
assert.equal(retornoSeguro('/?pagina=15&catalogo=1'),'/?pagina=15&catalogo=1');
assert.deepEqual(ventanaPaginas(1,1),[1]);assert.deepEqual(ventanaPaginas(3,5),[1,2,3,4,5]);
assert.deepEqual(ventanaPaginas(115,231),[1,'…',114,115,116,'…',231]);
assert.deepEqual(ventanaPaginas(231,231),[1,'…',230,231]);
console.log(`OK: ${pages} páginas, ${seen.length} códigos sin faltantes ni duplicados; filtros, URL, límites, elipsis y retorno interno.`);
